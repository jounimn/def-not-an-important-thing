import {createRequire} from 'node:module';
import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createPreviewServer} from './serve.mjs';
const require = createRequire('C:/Users/nilson.lopes/.agents/skills/df-design/package.json');
const {chromium} = require('playwright');
mkdirSync('captures', {recursive:true});
const browser = await chromium.launch({headless:true, channel:'msedge'});
const context = await browser.newContext({viewport:{width:1440,height:1000}, reducedMotion:'reduce'});
const page = await context.newPage();
const server=createPreviewServer();
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const previewUrl=`http://127.0.0.1:${server.address().port}`;
const errors=[];
const mediaRequests=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('request', r=>{if(r.url().endsWith('.mp4'))mediaRequests.push(r.url())});
const results=[];
const pass=(label)=>results.push(label);
try {
 await page.goto(previewUrl,{waitUntil:'networkidle'});
 assert.equal(mediaRequests.length,0); pass('No video request before login');
 await page.screenshot({path:'captures/login-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'captures/login-phone.png',fullPage:true});
 await page.locator('#username').fill('wrong-user');
 await page.locator('#username').press('Enter');
 await page.locator('#password').fill('wrong-password');
 await page.locator('#password').press('Enter');
 await page.locator('#login-error').filter({hasText:'não bateu'}).waitFor();
 assert.equal(await page.locator('#birthday-screen').isVisible(),false);pass('Incorrect credentials recover without entering birthday');
 const source=readFileSync('dist/app.js','utf8');
 const user=source.match(/value\.trim\(\) === '([^']+)'/)[1];
 const password=source.match(/\$\('password'\)\.value === '([^']+)'/)[1];
 await page.locator('#username').fill(user);
 await page.locator('#password').fill(password);
 await page.locator('#password').press('Enter');
 await page.locator('#video-section').waitFor({state:'visible'});
 await page.waitForFunction(()=>document.querySelector('video').readyState>=2,{},{timeout:20000});
 assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('pink')),true);
 assert.equal(await page.locator('video').evaluate(e=>e.muted),true);
 assert.equal(await page.locator('#birthday-log p').count(),5);pass('Correct login reveals pink theme, full birthday message and muted video');
 const metadata=await page.locator('video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration,ready:v.readyState}));
 results.push({video:metadata});
 await page.locator('video').evaluate(v=>v.pause());
 await page.screenshot({path:'captures/birthday-phone.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'captures/birthday-desktop.png',fullPage:true});
 await page.locator('#sound-button').click();
 assert.equal(await page.locator('video').evaluate(e=>e.muted),false);pass('Sound requires explicit button and toggles correctly');
 await page.locator('video').evaluate(v=>{v.pause();v.dispatchEvent(new Event('ended'))});
 await page.locator('#promo-section').waitFor({state:'visible'});
 assert.match(await page.locator('.current-price').innerText(),/8\.000/);pass('Video ended reveals olive-oil R$8.000 finale');
 await page.screenshot({path:'captures/promo-desktop.png',fullPage:true});
 for(const width of [320,360,390,768,1280,1920]) {
   await page.setViewportSize({width,height:900});
   const sizes=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
   assert.ok(sizes.scroll<=sizes.viewport,`horizontal overflow at ${width}: ${sizes.scroll}`);
 }
 pass('No horizontal overflow at 320, 360, 390, 768, 1280 and 1920px');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'captures/finale-phone.png',fullPage:true});
 await page.locator('#buy-button').click();
 await page.locator('#purchase-response').waitFor({state:'visible'});
 assert.match(await page.locator('#purchase-response').innerText(),/comprou mesmo/);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#purchase-response').isVisible(),false);pass('Fake purchase responds; Escape dismisses');
 await page.locator('#replay-button').click();
 await page.locator('#video-section').waitFor({state:'visible'});
 assert.equal(await page.locator('#promo-section').isVisible(),false);
 await page.locator('#skip-video').click();
 assert.equal(await page.locator('#promo-section').isVisible(),true);pass('Replay resets finale; skip reveals it again');
 await page.locator('#logout-button').click();
 assert.equal(await page.locator('#login-screen').isVisible(),true);
 assert.equal(await page.locator('video').getAttribute('src'),null);
 assert.equal(await page.locator('#password').inputValue(),'');
 pass('Logout stops/unloads video and resets credentials');
 assert.deepEqual(errors,[]);pass('No browser JavaScript errors');
 writeFileSync('captures/verification.json',JSON.stringify({status:'passed',results},null,2));
 console.log(JSON.stringify({status:'passed',results},null,2));
} catch(error) {
 await page.screenshot({path:'captures/failure.png',fullPage:true}).catch(()=>{});
 console.error(error);
 process.exitCode=1;
} finally { await browser.close(); server.close(); }
